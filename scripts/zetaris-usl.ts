// Runs Zetaris SQL files statement by statement and prints each result.
// Used for the Unified Semantic Layer deliverables (docs/ZETARIS_USL.md):
//
//   npm run zetaris:usl                                  # usl_create.sql then usl_queries.sql
//   npm run zetaris:usl -- data/zetaris/explore_ads_pg.sql [more files...]
//   npm run zetaris:usl -- --md out.md <files...>        # also write results as Markdown
//
// Unlike the agent's SQL tool this runner is NOT read-only: usl_create.sql
// compiles, activates and registers DQ rules, which needs the admin key
// (ZETARIS_API_KEY in .env). Statements end with ";" at the end of a line.
// A COMPILE USL statement keeps the CREATE TABLE definitions that follow it,
// because Zetaris needs a multi-table COMPILE sent as one request.

import fs from "node:fs";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { env, ROOT } from "../src/env.ts";
import { normalise } from "../src/zetaris/client.ts";

export interface Statement {
  sql: string;
  comment: string;
}

/** Splits a SQL file into statements; keeps comment lines just above each statement as its description. */
export function splitStatements(text: string): Statement[] {
  const out: Statement[] = [];
  let buf: string[] = [];
  let comment: string[] = [];
  const flush = () => {
    const sql = buf.join("\n").trim().replace(/;\s*$/, "");
    if (sql) {
      const prev = out[out.length - 1];
      if (prev && /^COMPILE\s+USL\b/i.test(prev.sql) && /^CREATE\s+TABLE\b/i.test(sql)) prev.sql += ";\n" + sql;
      else out.push({ sql, comment: (comment.join("\n").trim().split(/\n\s*\n/).pop() ?? "").replace(/\s+/g, " ") });
    }
    buf = [];
    comment = [];
  };
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim();
    if (!buf.length && (t.startsWith("--") || !t)) {
      if (t.startsWith("--")) comment.push(t.replace(/^--\s?/, ""));
      else if (comment.length && !t) comment.push("");
      continue;
    }
    buf.push(line);
    if (/;\s*(--.*)?$/.test(t)) flush();
  }
  flush();
  return out;
}

async function run(sql: string, limit = 50) {
  const url = env("ZETARIS_REST_URL", "http://localhost:8888/api/v1.0").replace(/\/+$/, "");
  const t0 = Date.now();
  const res = await fetch(`${url}/sql-editor/sqls/run`, {
    method: "POST",
    headers: {
      Authorization: `Bearer ${env("ZETARIS_API_KEY")}`,
      "X-Org-ID": env("ZETARIS_ORG_ID", "1"),
      "X-Request-ID": randomUUID(),
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ queryId: randomUUID(), sql, source: "SqlEditor", limit }),
    signal: AbortSignal.timeout(300_000),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`HTTP ${res.status}: ${text.slice(0, 600)}`);
  return { ...normalise(JSON.parse(text || "null")), ms: Date.now() - t0 };
}

const cell = (v: unknown) => {
  const s = (v === null || v === undefined ? "NULL" : typeof v === "object" ? JSON.stringify(v) : String(v)).replace(/\|/g, "\\|").replace(/\n/g, " ");
  return s.length > 240 ? `${s.slice(0, 240)}… (${s.length} chars)` : s;
};
function table(columns: string[], rows: unknown[][], max = 25): string {
  if (!columns.length) return "_(no columns returned)_";
  const lines = [`| ${columns.join(" | ")} |`, `|${columns.map(() => "---").join("|")}|`, ...rows.slice(0, max).map((r) => `| ${r.map(cell).join(" | ")} |`)];
  if (rows.length > max) lines.push(`\n_${rows.length - max} more rows not shown_`);
  return lines.join("\n");
}

async function main() {
  const args = process.argv.slice(2);
  let md: string | undefined;
  const mi = args.indexOf("--md");
  if (mi >= 0) [md] = args.splice(mi, 2).slice(1);
  const files = args.length ? args : ["data/zetaris/usl_create.sql", "data/zetaris/usl_queries.sql"];
  const report: string[] = [`<!-- generated by scripts/zetaris-usl.ts on ${new Date().toISOString()} -->`];
  let failed = 0;
  for (const f of files) {
    const stmts = splitStatements(fs.readFileSync(path.resolve(ROOT, f), "utf-8"));
    console.log(`\n=== ${f} (${stmts.length} statements)`);
    report.push(`\n### ${f}\n`);
    for (const [i, s] of stmts.entries()) {
      const head = s.sql.split("\n")[0].slice(0, 110);
      try {
        const r = await run(s.sql);
        console.log(`\n[${i + 1}] ${head}\n    ok, ${r.rows.length} rows, ${r.ms} ms`);
        if (r.rows.length) console.log(table(r.columns, r.rows, 15).split("\n").map((l) => "    " + l).join("\n"));
        report.push(`**[${i + 1}]** ${s.comment ? s.comment.split("\n")[0] : ""}\n\n\`\`\`sql\n${s.sql}\n\`\`\`\n\nResult (${r.rows.length} rows, ${r.ms} ms):\n\n${table(r.columns, r.rows)}\n`);
      } catch (e) {
        failed++;
        const msg = (e as Error).message;
        console.log(`\n[${i + 1}] ${head}\n    FAILED: ${msg}`);
        report.push(`**[${i + 1}]** ${s.comment ? s.comment.split("\n")[0] : ""}\n\n\`\`\`sql\n${s.sql}\n\`\`\`\n\nFAILED: \`${msg.slice(0, 400)}\`\n`);
      }
    }
  }
  if (md) fs.writeFileSync(path.resolve(ROOT, md), report.join("\n"));
  console.log(failed ? `\n${failed} statement(s) failed` : "\nall statements succeeded");
  process.exitCode = failed ? 1 : 0;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(ROOT, "scripts", "zetaris-usl.ts")) await main();
